let currentLang = (typeof localStorage !== 'undefined' && localStorage.getItem ? localStorage.getItem('cb_lang') : null) || 'hi';

export function getLanguage() {
  return currentLang;
}

export function setLanguage(langCode) {
  if (TRANSLATIONS[langCode]) {
    currentLang = langCode;
    localStorage.setItem('cb_lang', langCode);
  }
}

export function t(key, params = {}) {
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS['hi'];
  let text = dict[key] || TRANSLATIONS['hi'][key] || key;
  for (const [k, v] of Object.entries(params)) {
    text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
  }
  return text;
}
